//! Writes the Cargo manifest for a generated crate.

/// Turns a folder name such as `my-invoicing` into a crate name.
pub fn crate_name(folder_name: &str) -> String {
    let mut name: String = folder_name
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() {
                c.to_ascii_lowercase()
            } else {
                '_'
            }
        })
        .collect();
    if name.is_empty() || name.starts_with(|c: char| c.is_ascii_digit()) {
        name.insert_str(0, "dn_");
    }
    name
}

/// The empty `[workspace]` table stops Cargo from treating the generated
/// crate as part of any workspace the project folder happens to sit in.
pub fn cargo_manifest(crate_name: &str) -> String {
    format!(
        r#"# Generated by dn. Do not edit.
[package]
name = "{crate_name}"
version = "0.1.0"
edition = "2021"

[lib]
path = "src/lib.rs"

[workspace]
"#
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn makes_valid_crate_names() {
        assert_eq!(crate_name("my-invoicing"), "my_invoicing");
        assert_eq!(crate_name("2026"), "dn_2026");
    }
}
