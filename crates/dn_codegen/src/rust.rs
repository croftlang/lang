//! Generates a Rust module from a checked dn program.

use std::fmt::Write;

use dn_analysis::naming::to_snake_case;
use dn_analysis::{Program, Scope, Type, OUTPUT_NAME};
use dn_syntax::ast::*;

use crate::rust_names::rust_identifier;
use crate::source_text::expression_text;

const HEADER: &str = r#"// Generated by dn. Do not edit: change the .dn source and run `dn compile`.
#![allow(dead_code, unused_variables, unused_parens, clippy::all)]

/// A value that does not satisfy one of its constraints.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ConstraintViolation {
    pub constraint: &'static str,
    pub path: &'static str,
}

impl std::fmt::Display for ConstraintViolation {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "`{}` breaks constraint `{}`", self.path, self.constraint)
    }
}

impl std::error::Error for ConstraintViolation {}

/// Checks a value against the constraints declared on its struct and fields.
pub trait Validate {
    fn validate(&self) -> Result<(), ConstraintViolation>;
}
"#;

/// Generates the Rust source for a whole program.
pub fn generate_rust(program: &Program) -> String {
    let mut generator = RustGenerator {
        program,
        out: String::from(HEADER),
    };
    for item in &program.items {
        generator.out.push('\n');
        match item {
            Item::Const(decl) => generator.generate_const(decl),
            Item::Enum(decl) => generator.generate_enum(decl),
            Item::Struct(decl) => generator.generate_struct(decl),
            Item::Constraint(decl) => generator.generate_constraint(decl),
            Item::Port(decl) => generator.generate_port(decl),
            Item::Adapter(decl) => generator.generate_adapter(decl),
            Item::Function(decl) => generator.generate_function(decl),
        }
    }
    generator.out
}

struct RustGenerator<'a> {
    program: &'a Program,
    out: String,
}

/// How a value is passed into a generated constraint function.
fn parameter_type(ty: &Type) -> String {
    match ty {
        ty if ty.is_copy() => rust_type(ty),
        Type::String => "&str".to_string(),
        Type::List(item) => format!("&[{}]", rust_type(item)),
        other => format!("&{}", rust_type(other)),
    }
}

pub fn rust_type(ty: &Type) -> String {
    match ty {
        Type::Int => "i64".to_string(),
        Type::Float => "f64".to_string(),
        Type::Bool => "bool".to_string(),
        Type::String => "String".to_string(),
        Type::Unit => "()".to_string(),
        Type::List(item) => format!("Vec<{}>", rust_type(item)),
        Type::Option(item) => format!("Option<{}>", rust_type(item)),
        Type::Result(ok, error) => format!("Result<{}, {}>", rust_type(ok), rust_type(error)),
        Type::Struct(name) | Type::Enum(name) | Type::Generic(name) | Type::EnumName(name) => {
            name.clone()
        }
    }
}

fn constraint_function_name(constraint: &str) -> String {
    rust_identifier(&to_snake_case(constraint))
}

fn doc_comment(out: &mut String, indent: &str, text: &str) {
    for line in text.trim().lines() {
        if line.trim().is_empty() {
            let _ = writeln!(out, "{indent}///");
        } else {
            let _ = writeln!(out, "{indent}/// {}", line.trim());
        }
    }
}

impl<'a> RustGenerator<'a> {
    fn resolve_type(&self, ty: &TypeExpr, generics: &[Identifier]) -> Type {
        self.program
            .resolve_type(ty, generics)
            .expect("program has been checked")
    }

    fn type_of(&self, expr: &Expr, scope: &Scope) -> Type {
        self.program
            .type_of(expr, scope)
            .expect("program has been checked")
    }

    // ---- items ----

    fn generate_const(&mut self, decl: &ConstDecl) {
        let ty = match self.resolve_type(&decl.ty, &[]) {
            Type::String => "&str".to_string(),
            other => rust_type(&other),
        };
        let value = self.generate_expression(&decl.value, &Scope::new());
        let _ = writeln!(self.out, "pub const {}: {ty} = {value};", decl.name.name);
    }

    fn generate_enum(&mut self, decl: &EnumDecl) {
        let _ = writeln!(
            self.out,
            "#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]"
        );
        let _ = writeln!(self.out, "pub enum {} {{", decl.name.name);
        for variant in &decl.variants {
            let _ = writeln!(self.out, "    {},", variant.name);
        }
        let _ = writeln!(self.out, "}}");
    }

    fn generate_struct(&mut self, decl: &StructDecl) {
        let name = &decl.name.name;
        let _ = writeln!(self.out, "#[derive(Debug, Clone, PartialEq)]");
        let _ = writeln!(self.out, "pub struct {name} {{");
        for field in &decl.fields {
            let ty = rust_type(&self.resolve_type(&field.ty, &[]));
            let _ = writeln!(
                self.out,
                "    pub {}: {ty},",
                rust_identifier(&field.name.name)
            );
        }
        let _ = writeln!(self.out, "}}\n");

        let _ = writeln!(self.out, "impl Validate for {name} {{");
        let _ = writeln!(
            self.out,
            "    fn validate(&self) -> Result<(), ConstraintViolation> {{"
        );
        for field in &decl.fields {
            let field_name = rust_identifier(&field.name.name);
            let place = format!("self.{field_name}");
            let ty = self.resolve_type(&field.ty, &[]);
            let path = format!("{name}.{}", field.name.name);
            for constraint_use in &field.constraints {
                self.generate_constraint_check(constraint_use, &place, &ty, &path);
            }
            self.generate_nested_validation(&place, &ty);
        }
        for constraint_use in &decl.constraints {
            let ty = Type::Struct(name.clone());
            self.generate_constraint_check(constraint_use, "self", &ty, name);
        }
        let _ = writeln!(self.out, "        Ok(())");
        let _ = writeln!(self.out, "    }}");
        let _ = writeln!(self.out, "}}");
    }

    /// Emits `if !constraint(subject, arguments...) { return Err(...) }`.
    fn generate_constraint_check(
        &mut self,
        constraint_use: &ConstraintUse,
        place: &str,
        subject_type: &Type,
        path: &str,
    ) {
        let subject = if subject_type.is_copy() {
            place.to_string()
        } else if place == "self" {
            "self".to_string()
        } else {
            format!("&{place}")
        };
        let mut arguments = vec![subject];
        for argument in &constraint_use.arguments {
            arguments.push(self.generate_argument(argument, &Scope::new()));
        }
        let _ = writeln!(
            self.out,
            "        if !{}({}) {{",
            constraint_function_name(&constraint_use.name.name),
            arguments.join(", ")
        );
        let _ = writeln!(
            self.out,
            "            return Err(ConstraintViolation {{ constraint: {:?}, path: {path:?} }});",
            constraint_use.name.name
        );
        let _ = writeln!(self.out, "        }}");
    }

    /// Validates struct values held in a field, directly or inside a List or Option.
    fn generate_nested_validation(&mut self, place: &str, ty: &Type) {
        match ty {
            Type::Struct(_) => {
                let _ = writeln!(self.out, "        {place}.validate()?;");
            }
            Type::List(item) if matches!(**item, Type::Struct(_)) => {
                let _ = writeln!(self.out, "        for item in &{place} {{");
                let _ = writeln!(self.out, "            item.validate()?;");
                let _ = writeln!(self.out, "        }}");
            }
            Type::Option(item) if matches!(**item, Type::Struct(_)) => {
                let _ = writeln!(self.out, "        if let Some(item) = &{place} {{");
                let _ = writeln!(self.out, "            item.validate()?;");
                let _ = writeln!(self.out, "        }}");
            }
            _ => {}
        }
    }

    fn generate_constraint(&mut self, decl: &ConstraintDecl) {
        let mut scope = Scope::new();
        let mut parameters = Vec::new();
        for parameter in &decl.parameters {
            let ty = self.resolve_type(&parameter.ty, &decl.generics);
            parameters.push(format!(
                "{}: {}",
                rust_identifier(&parameter.name.name),
                parameter_type(&ty)
            ));
            scope.insert(parameter.name.name.clone(), ty);
        }
        let generics = if decl.generics.is_empty() {
            String::new()
        } else {
            let bounds: Vec<String> = decl
                .generics
                .iter()
                .map(|generic| format!("{}: PartialEq", generic.name))
                .collect();
            format!("<{}>", bounds.join(", "))
        };
        let body = self.generate_expression(&decl.body, &scope);
        let _ = writeln!(
            self.out,
            "/// Constraint `{}`: `{}`",
            decl.name.name,
            expression_text(&decl.body)
        );
        let _ = writeln!(
            self.out,
            "pub fn {}{generics}({}) -> bool {{",
            constraint_function_name(&decl.name.name),
            parameters.join(", ")
        );
        let _ = writeln!(self.out, "    {body}");
        let _ = writeln!(self.out, "}}");
    }

    fn resolve_signature(&self, signature: &Signature) -> (Vec<(String, Type)>, Type) {
        let parameters = signature
            .parameters
            .iter()
            .map(|parameter| {
                (
                    parameter.name.name.clone(),
                    self.resolve_type(&parameter.ty, &[]),
                )
            })
            .collect();
        (parameters, self.resolve_type(&signature.output, &[]))
    }

    fn generate_port(&mut self, decl: &PortDecl) {
        let _ = writeln!(self.out, "pub trait {} {{", decl.name.name);
        for operation in &decl.operations {
            let line = self.generate_operation_signature(operation);
            let _ = writeln!(self.out, "    {line};");
        }
        let _ = writeln!(self.out, "}}");
    }

    fn generate_operation_signature(&self, operation: &Signature) -> String {
        let (parameters, output) = self.resolve_signature(operation);
        let mut list = vec!["&self".to_string()];
        list.extend(
            parameters
                .iter()
                .map(|(name, ty)| format!("{}: {}", rust_identifier(name), rust_type(ty))),
        );
        format!(
            "fn {}({}) -> {}",
            rust_identifier(&operation.name.name),
            list.join(", "),
            rust_type(&output)
        )
    }

    fn generate_adapter(&mut self, decl: &AdapterDecl) {
        let port = self
            .program
            .port_decl(&decl.port.name)
            .expect("program has been checked");
        let _ = writeln!(
            self.out,
            "/// Adapter for port `{}`. Its operations are not generated yet.",
            port.name.name
        );
        let _ = writeln!(self.out, "pub struct {};\n", decl.name.name);
        let _ = writeln!(
            self.out,
            "impl {} for {} {{",
            port.name.name, decl.name.name
        );
        for operation in &port.operations {
            let line = self.generate_operation_signature(operation);
            let _ = writeln!(self.out, "    {line} {{");
            let _ = writeln!(
                self.out,
                "        todo!(\"adapter `{}` operation `{}`\")",
                decl.name.name, operation.name.name
            );
            let _ = writeln!(self.out, "    }}");
        }
        let _ = writeln!(self.out, "}}");
    }

    /// A function becomes two Rust functions: a public one that checks the
    /// contract, and a private `_body` one holding the implementation.
    fn generate_function(&mut self, decl: &FunctionDecl) {
        let name = rust_identifier(&decl.signature.name.name);
        let body_name = format!("{}_body", decl.signature.name.name);
        let (parameters, output) = self.resolve_signature(&decl.signature);

        let mut declared = Vec::new();
        let mut passed = Vec::new();
        for port in &decl.uses {
            let parameter = rust_identifier(&to_snake_case(&port.name));
            declared.push(format!("{parameter}: &dyn {}", port.name));
            passed.push(parameter);
        }
        let keep_inputs = !decl.ensures.is_empty();
        for (parameter, ty) in &parameters {
            let parameter_name = rust_identifier(parameter);
            declared.push(format!("{parameter_name}: {}", rust_type(ty)));
            if keep_inputs && !ty.is_copy() {
                passed.push(format!("{parameter_name}.clone()"));
            } else {
                passed.push(parameter_name);
            }
        }
        let declared = declared.join(", ");
        let output_type = rust_type(&output);

        if let Some(description) = &decl.description {
            doc_comment(&mut self.out, "", description);
        }
        if !decl.requires.is_empty() || !decl.ensures.is_empty() {
            let _ = writeln!(self.out, "///");
            for requirement in &decl.requires {
                let _ = writeln!(self.out, "/// Requires: `{}`", expression_text(requirement));
            }
            for guarantee in &decl.ensures {
                let _ = writeln!(self.out, "/// Ensures: `{}`", expression_text(guarantee));
            }
        }
        let _ = writeln!(self.out, "pub fn {name}({declared}) -> {output_type} {{");

        let mut scope: Scope = parameters.iter().cloned().collect();
        for (parameter, ty) in &parameters {
            if matches!(ty, Type::Struct(_)) {
                let parameter_name = rust_identifier(parameter);
                let _ = writeln!(
                    self.out,
                    "    debug_assert!({parameter_name}.validate().is_ok(), \"input `{parameter}` breaks its constraints\");"
                );
            }
        }
        for requirement in &decl.requires {
            let check = self.generate_expression(requirement, &scope);
            let _ = writeln!(
                self.out,
                "    debug_assert!({check}, {:?});",
                format!("requires failed: {}", expression_text(requirement))
            );
        }
        let call = format!("{body_name}({})", passed.join(", "));
        if decl.ensures.is_empty() {
            let _ = writeln!(self.out, "    {call}");
        } else {
            let _ = writeln!(self.out, "    let {OUTPUT_NAME} = {call};");
            scope.insert(OUTPUT_NAME.to_string(), output.clone());
            for guarantee in &decl.ensures {
                let check = self.generate_expression(guarantee, &scope);
                let _ = writeln!(
                    self.out,
                    "    debug_assert!({check}, {:?});",
                    format!("ensures failed: {}", expression_text(guarantee))
                );
            }
            let _ = writeln!(self.out, "    {OUTPUT_NAME}");
        }
        let _ = writeln!(self.out, "}}\n");

        let _ = writeln!(self.out, "fn {body_name}({declared}) -> {output_type} {{");
        let _ = writeln!(
            self.out,
            "    todo!(\"the body of `{}` has not been generated yet\")",
            decl.signature.name.name
        );
        let _ = writeln!(self.out, "}}");
    }

    // ---- expressions ----

    /// An argument to a constraint call: by value for copy types, otherwise
    /// borrowed. Borrowing a value that is already a reference is fine, as
    /// Rust's deref coercion turns `&&str` into `&str`, `&&[T]` into `&[T]`.
    fn generate_argument(&self, expr: &Expr, scope: &Scope) -> String {
        let code = self.generate_expression(expr, scope);
        if self.type_of(expr, scope).is_copy() {
            code
        } else {
            format!("&{code}")
        }
    }

    fn generate_expression(&self, expr: &Expr, scope: &Scope) -> String {
        match &expr.kind {
            ExprKind::Int(value) => value.to_string(),
            ExprKind::Float(value) => format!("{value:?}"),
            ExprKind::Bool(value) => value.to_string(),
            ExprKind::String(value) => format!("{value:?}"),
            ExprKind::Name(name) => {
                if scope.contains_key(name) {
                    rust_identifier(name)
                } else {
                    name.clone()
                }
            }
            ExprKind::Field(base, field) => {
                let base_type = self.type_of(base, scope);
                let base_code = self.generate_expression(base, scope);
                match (&base_type, field.name.as_str()) {
                    (Type::EnumName(enum_name), variant) => format!("{enum_name}::{variant}"),
                    (Type::List(_), "length") => format!("({base_code}.len() as i64)"),
                    (Type::String, "length") => format!("({base_code}.chars().count() as i64)"),
                    (Type::Option(_) | Type::Result(_, _), method) => {
                        format!("{base_code}.{method}()")
                    }
                    (_, field_name) => format!("{base_code}.{}", rust_identifier(field_name)),
                }
            }
            ExprKind::Call(name, arguments) => {
                let arguments: Vec<String> = arguments
                    .iter()
                    .map(|argument| self.generate_argument(argument, scope))
                    .collect();
                format!(
                    "{}({})",
                    constraint_function_name(&name.name),
                    arguments.join(", ")
                )
            }
            ExprKind::Unary(op, operand) => {
                let symbol = match op {
                    UnaryOp::Not => "!",
                    UnaryOp::Negate => "-",
                };
                format!("{symbol}({})", self.generate_expression(operand, scope))
            }
            ExprKind::Binary(op, left, right) => format!(
                "({} {} {})",
                self.generate_expression(left, scope),
                op.symbol(),
                self.generate_expression(right, scope)
            ),
        }
    }
}
