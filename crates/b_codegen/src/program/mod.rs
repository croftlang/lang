//! Putting the program together: the runtime, a header with every type and
//! prototype, and one C file with every function.

mod adapter;
mod builtin_storage;
mod command;
mod constant;
mod constraints;
mod equality;
mod events;
mod functions;
mod layout;
mod lookup;
mod main;
mod repository;
mod runtime;
mod serialize;
mod signature;

use crate::{GeneratedFile, Generator};

const RUNTIME_HEADER: &str = include_str!("../runtime/b.h");
const STDIO_FILES: &str = include_str!("../runtime/files.c");
const CURL_HTTP: &str = include_str!("../runtime/http.c");
const RUNTIME_SOURCE: &str = concat!(
    include_str!("../runtime/b_runtime.c"),
    include_str!("../runtime/decimal.c"),
    include_str!("../runtime/bytes.c"),
    include_str!("../runtime/saving.c"),
    include_str!("../runtime/text.c")
);

impl<'a> Generator<'a> {
    pub fn generate(&self) -> Result<Vec<GeneratedFile>, String> {
        let mut prototypes = Vec::new();
        let (defines, globals, init) = self.constants();
        let functions = self.functions(&mut prototypes);
        let commands = self.commands(&mut prototypes);
        let events = self.events(&mut prototypes);
        let (adapter_state, adapters) = self.adapters(&mut prototypes);
        let repositories = self.repositories(&mut prototypes);
        let serializers = self.serializer_functions();
        let storage = self.builtin_storage();
        let main = self.main_function();
        let error_names = self.error_names(&mut prototypes);
        let event_definition = self.event_definition();
        let equalities = self.equality_functions(&mut prototypes);
        let (check_prototypes, checks) = self.check_functions();
        let types = self.type_definitions();
        let natives = self.native_prototypes();

        let banner = format!(
            "/* Generated by b for target `{}`. Do not edit. */\n",
            self.target
        );
        let header = format!(
            "{banner}#ifndef B_PROGRAM_H\n#define B_PROGRAM_H\n\n#include \"b.h\"\n\n{types}{event_definition}{defines}\
             void b_init(void);\n{}\n\n{check_prototypes}/* Native functions the adapters call. */\n{natives}\n#endif\n",
            prototypes.join("\n")
        );
        let source = format!(
            "{banner}#include \"program.h\"\n\n{globals}\n{adapter_state}{init}{checks}{equalities}{functions}{commands}{events}{storage}{adapters}{serializers}{repositories}{error_names}{main}"
        );
        let runtime_header = RUNTIME_HEADER
            .replace(
                "#ifndef B_STRING_CAPACITY\n#define B_STRING_CAPACITY 32\n#endif",
                &format!("#define B_STRING_CAPACITY {}", self.sizes.string_capacity),
            )
            .replace(
                "#ifndef B_BYTES_CAPACITY\n#define B_BYTES_CAPACITY 64\n#endif",
                &format!("#define B_BYTES_CAPACITY {}", self.sizes.bytes_capacity),
            );
        let standard_natives = self.standard_natives();
        let reached: String = standard_natives
            .iter()
            .map(|file| file.contents.as_str())
            .collect();
        let mut files = vec![
            GeneratedFile {
                name: "b.h".to_string(),
                contents: runtime_header,
            },
            GeneratedFile {
                name: "b_runtime.c".to_string(),
                // `b_fail` is always kept: `B_CHECK` in b.h calls it.
                contents: runtime::trim_runtime(
                    RUNTIME_SOURCE,
                    &format!("b_fail\n{header}{source}{reached}"),
                ),
            },
            GeneratedFile {
                name: "program.h".to_string(),
                contents: header,
            },
            GeneratedFile {
                name: "program.c".to_string(),
                contents: source,
            },
        ];
        files.extend(standard_natives);
        Ok(files)
    }

    /// The C for standard adapters this target binds: `b_files.c` when
    /// `Files` is bound to `StdioFiles`, and `b_http.c` for `CurlHttp`.
    fn standard_natives(&self) -> Vec<GeneratedFile> {
        let binds = |context: &str, name: &str| {
            (self.bindings.values())
                .any(|adapter| adapter.context == context && adapter.name == name)
        };
        let mut files = Vec::new();
        if binds("Std.Files", "StdioFiles") {
            files.push(GeneratedFile {
                name: "b_files.c".to_string(),
                contents: STDIO_FILES.to_string(),
            });
        }
        if binds("Std.Http", "CurlHttp") {
            files.push(GeneratedFile {
                name: "b_http.c".to_string(),
                contents: CURL_HTTP.to_string(),
            });
        }
        files
    }

    fn native_prototypes(&self) -> String {
        let mut natives = self.natives.borrow().clone();
        natives.sort();
        natives.dedup_by(|a, b| a.0 == b.0);
        natives
            .into_iter()
            .map(|(_, prototype)| format!("{prototype}\n"))
            .collect()
    }
}
